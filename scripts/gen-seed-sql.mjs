// Generates supabase/migrations/20261024000500_patrol_seed.sql from src/domain/categories.seed.json
// (single source of truth for default categories). Run: node scripts/gen-seed-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = import.meta.url.startsWith('file:') ? fileURLToPath(import.meta.url).replace(/scripts[\/]gen-seed-sql.mjs$/, '') : process.cwd() + '/';
const seed = JSON.parse(readFileSync(root + 'src/domain/categories.seed.json', 'utf8'));
const json = JSON.stringify(seed).replaceAll("'", "''");

export const sql = `-- Lion Patrol v2 — default report categories (GENERATED by scripts/gen-seed-sql.mjs from
-- src/domain/categories.seed.json; do not edit by hand). Re-runnable.
begin;

create or replace function public.patrol_default_categories()
returns jsonb language sql immutable set search_path = public as $seed$
  select '${json}'::jsonb
$seed$;

-- Inserts missing default categories/subtypes for an org. Idempotent (matches by name).
create or replace function public.patrol_seed_categories_internal(p_org uuid)
returns integer language plpgsql security definer set search_path = public as $$
declare
  c jsonb; s text; v_cat uuid; v_added integer := 0; v_sort integer; v_sub_sort integer;
  v_max integer;
begin
  select coalesce(max(sort), -1) into v_max from public.patrol_categories where org_id = p_org;
  v_sort := 0;
  for c in select * from jsonb_array_elements(public.patrol_default_categories()) loop
    select id into v_cat from public.patrol_categories where org_id = p_org and lower(name) = lower(c->>'name');
    if v_cat is null then
      insert into public.patrol_categories (org_id, name, color, icon, sort, required_fields, default_severity, use_for)
      values (p_org, c->>'name', c->>'color', c->>'icon', v_max + 1 + v_sort,
              array(select jsonb_array_elements_text(c->'required_fields')),
              (c->>'default_severity')::public.patrol_severity, c->>'use_for')
      returning id into v_cat;
      v_added := v_added + 1;
    end if;
    v_sub_sort := 0;
    for s in select * from jsonb_array_elements_text(c->'subtypes') loop
      insert into public.patrol_subtypes (org_id, category_id, name, sort)
      values (p_org, v_cat, s, v_sub_sort)
      on conflict do nothing;
      v_sub_sort := v_sub_sort + 1;
    end loop;
    v_sort := v_sort + 1;
  end loop;
  return v_added;
end $$;

revoke all on function public.patrol_default_categories() from public, anon;
grant execute on function public.patrol_default_categories() to authenticated;
revoke all on function public.patrol_seed_categories_internal(uuid) from public, anon, authenticated;

commit;
`;

if (import.meta.url.startsWith('file:') && process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(root + 'supabase/migrations/20261024000500_patrol_seed.sql', sql);
  console.log('wrote 20261024000500_patrol_seed.sql');
}
